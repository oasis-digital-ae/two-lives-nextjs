// Ports every page of the static site into this app.
//
//   node tools/port-pages.mjs ../two-lives
//
// Routes:
//   index.html                -> app/(home)/page.tsx                 body: custom-cursor index-page
//   request-mentorship.html   -> app/(contact)/request-mentorship/   body: custom-cursor non-home contactpage
//   404.html                  -> content/not-found.tsx (used by app/global-not-found.tsx)
//   <page>.html               -> app/(site)/<page>/page.tsx          body: custom-cursor non-home
//   case-study/<x>.html       -> app/(site)/case-study/<x>/page.tsx
//   journal/<slug>.html       -> content/journal/<slug>.tsx + content/journal/index.ts (slug map)
//   blog/<slug>.html          -> content/blog/<slug>.tsx   + content/blog/index.ts
//
// Also copies every image/font/subtitle file the pages or the stylesheets reference into
// public/, and prints any page whose scripts are not handled by a layout here so they can
// be dealt with by hand.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const STATIC = process.argv[2];
if (!STATIC) { console.error("usage: node tools/port-pages.mjs <static site checkout>"); process.exit(1); }
const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const CONVERT = path.join(ROOT, "tools/convert-html.mjs");
const KNOWN_SCRIPTS = new Set(["js/jquery.js", "js/vendors.min.js", "js/main.min.js", "js/app.min.js", "/js/jquery.js", "/js/vendors.min.js", "/js/main.min.js", "/js/app.min.js",
  "https://unpkg.com/@supabase/supabase-js@2", "https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2", "/js/recent-posts.js", "/js/blog-recent-posts.js", "js/blog-metro.js", "js/blogs-metro.js",
  "https://assets.calendly.com/assets/external/widget.js"]);

const pascal = (s) => s.replace(/(^|[^a-z0-9]+)([a-z0-9])/gi, (_, __, c) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, "") || "Page";
const reportDir = fs.mkdtempSync("/tmp/port-reports-");
const notes = [];

function convert(src, out, name) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const report = path.join(reportDir, path.basename(out) + ".json");
  execFileSync("node", [CONVERT, src, out, report, name], { stdio: ["ignore", "ignore", "inherit"] });
  const r = JSON.parse(fs.readFileSync(report, "utf8"));
  const unknown = r.externalScripts.filter((s) => !KNOWN_SCRIPTS.has(s));
  const extras = r.externalScripts.filter((s) => !/^\/?js\/(jquery|vendors\.min|main\.min|app\.min)\.js$/.test(s));
  if (unknown.length || r.inlineStyles.length || r.warnings.length || r.important.length) notes.push(`${path.relative(STATIC, src)}: unknown scripts ${JSON.stringify(unknown)} inline styles ${r.inlineStyles.length} important ${r.important.length} warnings ${JSON.stringify(r.warnings)}`);
  return { ...r, extras };
}

const html = (dir) => fs.readdirSync(path.join(STATIC, dir)).filter((f) => f.endsWith(".html")).map((f) => path.join(dir, f));
const pages = {}; // route -> extras, for the summary

// top-level pages
for (const file of html(".")) {
  const slug = path.basename(file, ".html");
  let out, name = pascal(slug) + "Page";
  if (slug === "index") out = "app/(home)/page.tsx";
  else if (slug === "request-mentorship") out = "app/(contact)/request-mentorship/page.tsx";
  else if (slug === "404") { out = "content/not-found.tsx"; name = "NotFoundBody"; }
  // listing pages sit in a nested route group so they get their own layout (scripts) next to the [slug] route
  else if (slug === "journal" || slug === "blog") out = `app/(site)/${slug}/(index)/page.tsx`;
  else out = `app/(site)/${slug}/page.tsx`;
  pages["/" + (slug === "index" ? "" : slug)] = convert(path.join(STATIC, file), path.join(ROOT, out), name).extras;
}
for (const file of html("case-study")) {
  const slug = path.basename(file, ".html");
  pages["/case-study/" + slug] = convert(path.join(STATIC, file), path.join(ROOT, `app/(site)/case-study/${slug}/page.tsx`), pascal(slug) + "CaseStudy").extras;
}
// posts -> content modules + slug map
for (const section of ["journal", "blog"]) {
  const slugs = [];
  for (const file of html(section)) {
    const slug = path.basename(file, ".html");
    slugs.push(slug);
    pages[`/${section}/${slug}`] = convert(path.join(STATIC, file), path.join(ROOT, `content/${section}/${slug}.tsx`), pascal(slug)).extras;
  }
  const index = `// GENERATED by tools/port-pages.mjs: one entry per post, loaded on demand.
import type { Metadata } from "next";
import type { ComponentType } from "react";

export type PostModule = { default: ComponentType; metadata: Metadata };

export const posts: Record<string, () => Promise<PostModule>> = {
${slugs.sort().map((s) => `  ${JSON.stringify(s)}: () => import(${JSON.stringify("./" + s)}),`).join("\n")}
};
`;
  fs.writeFileSync(path.join(ROOT, `content/${section}/index.ts`), index);
}

// assets referenced by any page or stylesheet
const sources = [...html("."), ...html("case-study"), ...html("journal"), ...html("blog"), "css/site.min.css", "css/blog-detail.css"].map((f) => fs.readFileSync(path.join(STATIC, f), "utf8")).join("\n");
const refs = new Set();
for (const m of sources.matchAll(/(?:url=|url\(["']?|src=["']|href=["']|srcset=["'])\/?((?:images|img|fonts|subtitles)\/[A-Za-z0-9_\-./]+?\.[a-z0-9]{2,5})/gi)) refs.add(m[1]);
for (const m of sources.matchAll(/\/?((?:images|img)\/[A-Za-z0-9_\-./]+?\.(?:webp|svg|png|jpe?g|mp4|gif))(?=[&"' )])/g)) refs.add(m[1]);
let copied = 0, missing = [];
for (const r of refs) {
  const src = path.join(STATIC, r);
  if (!fs.existsSync(src)) { missing.push(r); continue; }
  const dst = path.join(ROOT, "public", r);
  if (fs.existsSync(dst) && fs.statSync(dst).size === fs.statSync(src).size) continue;
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst); copied++;
}
for (const f of ["css/site.min.css", "css/blog-detail.css", "robots.txt", "sitemap.xml"]) {
  fs.mkdirSync(path.dirname(path.join(ROOT, "public", f)), { recursive: true });
  fs.copyFileSync(path.join(STATIC, f), path.join(ROOT, "public", f));
}

console.log(`ported ${Object.keys(pages).length} pages; copied ${copied} new assets; ${missing.length} referenced files do not exist in the static site (${missing.slice(0, 6).join(", ")}${missing.length > 6 ? ", ..." : ""})`);
console.log("pages with extra scripts:");
for (const [route, extras] of Object.entries(pages)) if (extras.length) console.log(`  ${route}: ${extras.join(", ")}`);
if (notes.length) { console.log("needs attention:"); notes.forEach((n) => console.log("  " + n)); }
