                <ul>
                  <li>
                    <strong>Shift Perspective</strong>
                    : Rather than viewing failure as a negative outcome, see it as an opportunity for growth. Analyse what went wrong and identify areas for improvement.
                  </li>
                  <li>
                    <strong>Practise Resilience</strong>
                    : Develop resilience by reflecting on past failures and the lessons learned. This practice can help athletes build a stronger mindset for future challenges.
                  </li>
                  <li>
                    <strong>Celebrate Small Wins</strong>
                    : Recognise and celebrate progress, no matter how small. This positive reinforcement can help maintain motivation and a growth-oriented mindset.
                  </li>
                </ul>
